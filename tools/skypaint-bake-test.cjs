'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {patchCloudShader,encodeRadiance,captureViews,sourceManifest,buildFixture,assertCaptureRadianceFits}=require('./skypaint-bake-source.cjs');
const source=fs.readFileSync(path.join(process.env.SKYPAINT_SOURCE||'../SkyPaint','src/render/cloud.glsl'),'utf8');
const patched=patchCloudShader(source);
assert(patched.includes('radiance+=transmission*alpha*lit;'));
assert(patched.includes('transmission*=1.0-alpha;'));
assert(patched.includes('vec3 lit=studioLight(p,rd);'));
assert(patched.includes('uBakeMode==1'));
assert(patched.includes('bakeWeight+=contribution;'));
assert.throws(()=>patchCloudShader(source.replace('radiance+=transmission*alpha*lit;','changed;')),/source changed/);
assert.throws(()=>patchCloudShader(patched),/already patched/);
assert.deepEqual([...encodeRadiance([1,0,4,.5],4)],[128,0,255,128]);
assert.deepEqual([...encodeRadiance([3,2,1,0],4)],[0,0,0,0]);
assert.throws(()=>encodeRadiance([0,0,0,1],0),/scale/);
let rawReads=0;
assert.equal(assertCaptureRadianceFits(new Uint8Array([211,140,90,255]),()=>{rawReads++;throw Error('Ordinary capture must not read float pixels');},4,{yaw:35,pitch:-85}),false);
assert.equal(rawReads,0);
assert.equal(assertCaptureRadianceFits(new Uint8Array([255,140,90,255]),()=>{rawReads++;return new Float32Array([4,1,1,1]);},4,{yaw:35,pitch:-85}),true);
assert.equal(rawReads,1);
assert.throws(()=>assertCaptureRadianceFits(new Uint8Array([255,140,90,255]),()=>new Float32Array([4.25,1,1,1]),4,{yaw:35,pitch:-85}),/Radiance exceeds.*yaw 35.*pitch -85/);
assert.throws(()=>assertCaptureRadianceFits(new Uint8Array([255,140,90,255]),()=>new Float32Array([4,6,1,1]),4,{yaw:-35,pitch:20}),/increase radianceScale/);
const views=captureViews();assert.equal(views.length,15);
assert(views.some(v=>v.pitch===-85));assert(views.some(v=>v.pitch===20));
assert.equal(new Set(views.map(v=>JSON.stringify(v))).size,15);
const manifest=sourceManifest(process.env.SKYPAINT_SOURCE||'../SkyPaint');
assert(manifest.files['src/render/studio-lighting.glsl'].length===64);
async function browserApiCpu(){
 const vm=require('node:vm'),scope={window:{},TextEncoder,TextDecoder,performance,URL,DOMException,setTimeout,clearTimeout,structuredClone};
 const bundle=await buildFixture(process.env.SKYPAINT_SOURCE||'../SkyPaint');
 for(const notice of ['Copyright © 2010-2026 three.js authors','Copyright (c) 2026 Cloud Nodes Studio contributors','Copyright (C) 2014-2017 by Vitaly Puzrin and Andrei Tuputcyn','(C) 1995-2013 Jean-loup Gailly and Mark Adler','Permission is hereby granted, free of charge'])assert(bundle.includes(notice),'Bundle missing license notice: '+notice);
 vm.runInNewContext(bundle,scope);
 const create=scope.window.createSkyPaintBake;
 const prepare=scope.window.prepareSkyPaintBakeScene;
 assert.equal(typeof prepare,'function');
 assert.equal(typeof create,'function');assert.equal(scope.window.SKYPAINT_BAKE_SOURCE.views.length,15);
 await assert.rejects(create({w:17,h:12}),/dimensions/);
 await assert.rejects(create({radianceScale:0}),/radiance scale/);
 await assert.rejects(create({radianceScale:1e300}),/radiance scale/);
 await assert.rejects(create({radianceScale:1e-300}),/radiance scale/);
 await assert.rejects(create({scene:'{}'}),/missing or unsupported fields/);
 // Schema validation and cancellation precede viewer/GPU allocation.
 await assert.rejects(create({signal:{aborted:true}}),e=>e.name==='AbortError');
 for(const radianceScale of [1e-6,65504])await assert.rejects(create({radianceScale,signal:{aborted:true}}),e=>e.name==='AbortError');
 const json=fs.readFileSync(path.join(__dirname,'../assets/skypaint-default.js'),'utf8');
 const asset=JSON.parse(json.slice(json.indexOf('=')+1).trim().replace(/;$/,''));
 const savedScene=asset.recipe.scene||asset.recipe.capture.scene;
 const original=JSON.stringify(savedScene),valid=await prepare({scene:original});
 assert.equal(JSON.stringify(valid.scene),original);assert.equal(JSON.stringify(valid.evaluated),original);
 // Use SkyPaint's real sculpt fixture and evaluator; do not substitute a fake field.
 const sourceRoot=path.resolve(process.env.SKYPAINT_SOURCE||'../SkyPaint'),esbuild=require(path.join(sourceRoot,'node_modules/esbuild'));
 const fixtureCode='export {sculptStudy} from '+JSON.stringify(path.join(sourceRoot,'src/core/sculpt-studies.js').replaceAll('\\','/'))+'; export {compressSceneStorage} from '+JSON.stringify(path.join(sourceRoot,'src/core/scene-compression.js').replaceAll('\\','/'))+';';
 const fixture=await esbuild.build({stdin:{contents:fixtureCode,resolveDir:sourceRoot},bundle:true,write:false,platform:'node',format:'cjs',logLevel:'silent'});
 const core={exports:{}},coreScope={module:core,exports:core.exports,TextEncoder,TextDecoder,structuredClone};vm.runInNewContext(fixture.outputFiles[0].text,coreScope);
 const sculpt=core.exports.sculptStudy('sphere'),sculptText=JSON.stringify(sculpt),flat=await prepare({scene:sculptText});
 assert.equal(JSON.stringify(flat.scene),sculptText);assert.equal(flat.scene.volumes[0].recipe.field.format,'sky-paint-sculpt-program-v1');
 assert.equal(flat.evaluated.volumes[0].recipe.field.format,'sky-paint-sdf-q16-v1');assert.equal(flat.evaluated.volumes[0].recipe.field.data,flat.scene.volumes[0].recipe.field.base.data);
 assert.equal(JSON.stringify(sculpt),sculptText);
 const stroked=JSON.parse(sculptText);stroked.volumes[0].recipe.field.layers[0].strokes=[{id:1,mode:'carve',radius:.4,gain:.8,centers:[[.3,.2,.5]]}];
 const strokedText=JSON.stringify(stroked),replayed=await prepare({scene:strokedText});assert.equal(JSON.stringify(replayed.scene),strokedText);
 assert.notEqual(replayed.evaluated.volumes[0].recipe.field.data,stroked.volumes[0].recipe.field.base.data);
 const compressed=core.exports.compressSceneStorage(stroked),compressedText=JSON.stringify(compressed),expanded=await prepare({scene:compressedText});
 assert.equal(expanded.scene.volumes[0].recipe.field.base.format,'sky-paint-sdf-q16-xdelta-zlib-v1');assert.equal(JSON.stringify(expanded.scene),compressedText);
 assert.equal(expanded.evaluated.volumes[0].recipe.field.data,replayed.evaluated.volumes[0].recipe.field.data);
 await assert.rejects(prepare({scene:strokedText,signal:{aborted:true}}),e=>e.name==='AbortError');
 await assert.rejects(create({scene:JSON.stringify(savedScene),signal:{aborted:true}}),e=>e.name==='AbortError');
 const scene=structuredClone(savedScene);scene.render.look.enabled=false;
 await assert.rejects(create({scene:JSON.stringify(scene)}),/Enable Studio lighting/);
 console.log('SkyPaint bake CPU contracts and author API validation passed');
}
browserApiCpu().catch(error=>{console.error(error);process.exitCode=1;});
